-- Smart Recipes schema (Postgres / Neon), reference copy of the smart_recipes schema.
-- Row level security is not used; the app connects as the table owner.
-- Table names are unqualified: run it with search_path set to smart_recipes (src/lib/db.ts).

CREATE TABLE failed_ingest (
    id bigint NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    url text NOT NULL,
    error text
);
ALTER TABLE failed_ingest ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME "failed-ingest_id_seq"
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
CREATE TABLE ingredient (
    id integer NOT NULL,
    label text NOT NULL,
    sort smallint,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    recipe_id integer NOT NULL,
    unit_id integer
);
ALTER TABLE ingredient ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME ingredient_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
CREATE TABLE recipe (
    id bigint NOT NULL,
    name text NOT NULL,
    description text,
    created_at timestamp with time zone DEFAULT now(),
    url text,
    primary_image text,
    category text,
    cuisine text,
    keywords text,
    uuid uuid DEFAULT gen_random_uuid() NOT NULL
);
ALTER TABLE recipe ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME recipe_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
CREATE TABLE steps (
    id bigint NOT NULL,
    label text NOT NULL,
    sort integer NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    recipe_id integer NOT NULL,
    section text,
    text text
);
ALTER TABLE steps ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME steps_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
CREATE TABLE unit (
    id integer NOT NULL,
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    label text NOT NULL,
    abbreviation text NOT NULL
);
ALTER TABLE unit ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME unit_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
CREATE TABLE users (
    id bigint NOT NULL,
    email text NOT NULL,
    name text,
    created_at timestamp with time zone DEFAULT now() NOT NULL
);
ALTER TABLE users ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME user_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
CREATE TABLE user_recipe (
    created_at timestamp with time zone DEFAULT now() NOT NULL,
    user_id bigint NOT NULL,
    recipe_id bigint NOT NULL
);
ALTER TABLE ONLY failed_ingest
    ADD CONSTRAINT "failed-ingest_pkey" PRIMARY KEY (id);
ALTER TABLE ONLY ingredient
    ADD CONSTRAINT ingredient_pkey PRIMARY KEY (id);
ALTER TABLE ONLY recipe
    ADD CONSTRAINT recipe_pkey PRIMARY KEY (id);
ALTER TABLE ONLY steps
    ADD CONSTRAINT steps_pkey PRIMARY KEY (id);
ALTER TABLE ONLY unit
    ADD CONSTRAINT unit_pkey PRIMARY KEY (id);
ALTER TABLE ONLY users
    ADD CONSTRAINT user_email_key UNIQUE (email);
ALTER TABLE ONLY users
    ADD CONSTRAINT user_pkey PRIMARY KEY (id);
ALTER TABLE ONLY user_recipe
    ADD CONSTRAINT user_recipe_pkey PRIMARY KEY (user_id, recipe_id);
ALTER TABLE ONLY ingredient
    ADD CONSTRAINT ingredient_recipe_id_fkey FOREIGN KEY (recipe_id) REFERENCES recipe(id) ON DELETE CASCADE;
ALTER TABLE ONLY ingredient
    ADD CONSTRAINT ingredient_unit_id_fkey FOREIGN KEY (unit_id) REFERENCES unit(id) ON DELETE SET NULL;
ALTER TABLE ONLY steps
    ADD CONSTRAINT steps_recipe_id_fkey FOREIGN KEY (recipe_id) REFERENCES recipe(id) ON DELETE CASCADE;
ALTER TABLE ONLY user_recipe
    ADD CONSTRAINT user_recipe_recipe_id_fkey FOREIGN KEY (recipe_id) REFERENCES recipe(id) ON DELETE CASCADE;
ALTER TABLE ONLY user_recipe
    ADD CONSTRAINT user_recipe_user_id_fkey FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE;
